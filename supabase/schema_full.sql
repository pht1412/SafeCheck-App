    INTO v_pairing_code
    FROM generate_series(1, 6);
  END IF;

  INSERT INTO public.profiles (id, email, full_name, role, phone, pairing_code)
  VALUES (
    NEW.id,
    NEW.email,
    v_full_name,
    v_role,
    v_phone,
    v_pairing_code
  )
