      full_name = EXCLUDED.full_name,
      role = EXCLUDED.role,
      phone = EXCLUDED.phone,
      pairing_code = COALESCE(public.profiles.pairing_code, EXCLUDED.pairing_code);

  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Lỗi trong handle_new_user: %', SQLERRM;
  RETURN NEW;
END;
$$;

