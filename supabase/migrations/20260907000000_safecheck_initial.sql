-- 1. Bật Extensions cần thiết
CREATE EXTENSION IF NOT EXISTS pg_cron;

-- 2. Đảm bảo cấu trúc các bảng
CREATE TABLE IF NOT EXISTS configurations (
  family_code VARCHAR PRIMARY KEY,
  checkin_start TIME NOT NULL DEFAULT '07:00:00',
  checkin_deadline TIME NOT NULL DEFAULT '09:00:00',
  emergency_buffer_minutes INT NOT NULL DEFAULT 30,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS checkin_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_code VARCHAR NOT NULL,
  log_date DATE NOT NULL DEFAULT CURRENT_DATE,
  status VARCHAR NOT NULL DEFAULT 'Waiting',
  checkin_time TIMESTAMPTZ,
  source VARCHAR,
  ping_requested_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT now(),
  CONSTRAINT unique_family_date UNIQUE (family_code, log_date)
);

-- Thêm cột ping_requested_at nếu bảng đã tồn tại từ trước
ALTER TABLE checkin_logs 
ADD COLUMN IF NOT EXISTS ping_requested_at TIMESTAMPTZ;

