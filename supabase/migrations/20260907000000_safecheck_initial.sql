-- 4.1. Hàm quét trễ giờ, quá hạn, overdue ping
CREATE OR REPLACE FUNCTION check_overdue_routine()
RETURNS VOID AS $$
BEGIN
  -- Quá hạn chốt mà vẫn Waiting -> Chuyển thành Late
  UPDATE checkin_logs log
  SET status = 'Late'
  FROM configurations cfg
  WHERE log.family_code = cfg.family_code
    AND log.log_date = CURRENT_DATE
    AND log.status = 'Waiting'
    AND CURRENT_TIME > cfg.checkin_deadline;

  -- Quá hạn buffer phút sau Late -> Chuyển thành Emergency
  UPDATE checkin_logs log
  SET status = 'Emergency'
  FROM configurations cfg
  WHERE log.family_code = cfg.family_code
    AND log.log_date = CURRENT_DATE
    AND log.status = 'Late'
    AND CURRENT_TIME > (cfg.checkin_deadline + (cfg.emergency_buffer_minutes || ' minutes')::INTERVAL);

  -- Quá 15 phút từ lúc Ping mà Cụ chưa phản hồi -> Chuyển thành Overdue_Ping
  UPDATE checkin_logs
  SET status = 'Overdue_Ping'
  WHERE log_date = CURRENT_DATE
    AND status = 'Ping_Requested'
    AND (now() - ping_requested_at) > INTERVAL '15 minutes';
END;
$$ LANGUAGE plpgsql;

-- 4.2. Hàm tự động reset tạo bản ghi ngày mới lúc 00:00
CREATE OR REPLACE FUNCTION reset_daily_routine()
RETURNS VOID AS $$
BEGIN
  INSERT INTO checkin_logs (family_code, log_date, status)
  SELECT family_code, CURRENT_DATE, 'Waiting'
  FROM configurations
  ON CONFLICT (family_code, log_date) DO NOTHING;
END;
$$ LANGUAGE plpgsql;

-- --------------------------------------------------------------------
-- 5. ĐĂNG KÝ LỊCH CRON JOB (Chỉ đăng ký nếu chưa có)
-- --------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'auto-detect-late-elderly') THEN
    PERFORM cron.schedule(
      'auto-detect-late-elderly',
      '* * * * *',
      'SELECT check_overdue_routine()'
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'auto-reset-daily') THEN
    PERFORM cron.schedule(
      'auto-reset-daily',
      '0 0 * * *',
      'SELECT reset_daily_routine()'
    );
  END IF;
END $$;
