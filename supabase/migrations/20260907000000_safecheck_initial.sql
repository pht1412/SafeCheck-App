-- 3.1. Điểm danh hàng ngày (Flow 1 & Flow 4)
CREATE OR REPLACE FUNCTION perform_checkin(p_family_code VARCHAR)
RETURNS JSON AS $$
DECLARE
  v_current_time TIME := CURRENT_TIME;
  v_cfg RECORD;
BEGIN
  SELECT * INTO v_cfg FROM configurations WHERE family_code = p_family_code;
  
  IF NOT FOUND THEN
    RETURN json_build_object('success', false, 'message', 'Mã gia đình không tồn tại');
  END IF;

  IF v_current_time < v_cfg.checkin_start THEN
    RETURN json_build_object('success', false, 'message', 'Chưa đến khung giờ điểm danh');
  END IF;

  UPDATE checkin_logs
  SET status = 'Safe',
      checkin_time = now(),
      source = 'Daily_Button'
  WHERE family_code = p_family_code 
    AND log_date = CURRENT_DATE;

  RETURN json_build_object('success', true, 'message', 'Điểm danh an toàn thành công');
END;
$$ LANGUAGE plpgsql;

-- 3.2. Con cháu gửi yêu cầu chuông kiểm tra (Flow 4)
CREATE OR REPLACE FUNCTION request_ping(p_family_code VARCHAR)
RETURNS JSON AS $$
DECLARE
  v_last_ping TIMESTAMPTZ;
BEGIN
  SELECT ping_requested_at INTO v_last_ping
  FROM checkin_logs
  WHERE family_code = p_family_code AND log_date = CURRENT_DATE;

  IF v_last_ping IS NOT NULL AND (now() - v_last_ping) < INTERVAL '15 minutes' THEN
    RETURN json_build_object(
      'success', false, 
      'message', 'Đang trong thời gian chờ (cooldown 15 phút)'
    );
  END IF;

  UPDATE checkin_logs
  SET status = 'Ping_Requested',
      ping_requested_at = now()
  WHERE family_code = p_family_code AND log_date = CURRENT_DATE;

  RETURN json_build_object('success', true, 'message', 'Đã phát chuông kiểm tra tới máy Cụ');
END;
$$ LANGUAGE plpgsql;

-- 3.3. Kích hoạt khẩn cấp SOS (Flow 3)
CREATE OR REPLACE FUNCTION trigger_sos(p_family_code VARCHAR)
RETURNS JSON AS $$
BEGIN
  UPDATE checkin_logs
  SET status = 'Emergency',
      source = 'SOS'
  WHERE family_code = p_family_code AND log_date = CURRENT_DATE;

  RETURN json_build_object('success', true, 'message', 'Đã kích hoạt báo động khẩn cấp');
END;
$$ LANGUAGE plpgsql;

-- 3.4. Con cháu tắt báo động / Xác nhận an toàn (Flow 5)
CREATE OR REPLACE FUNCTION resolve_alarm(p_family_code VARCHAR)
RETURNS JSON AS $$
BEGIN
  UPDATE checkin_logs
  SET status = 'Safe'
  WHERE family_code = p_family_code AND log_date = CURRENT_DATE;

  RETURN json_build_object('success', true, 'message', 'Đã tắt báo động, xác nhận an toàn');
END;
$$ LANGUAGE plpgsql;

